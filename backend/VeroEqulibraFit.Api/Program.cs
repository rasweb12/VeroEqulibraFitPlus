using VeroEqulibraFit.Application.Exercises;
using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.AspNetCore.RateLimiting;
using Microsoft.IdentityModel.Tokens;
using VeroEqulibraFit.Infrastructure;
using VeroEqulibraFit.Api.Services;
using System.Threading.RateLimiting;
using System.Net;
using Microsoft.AspNetCore.HttpOverrides;
using Microsoft.AspNetCore.Diagnostics.HealthChecks;
using Microsoft.AspNetCore.DataProtection;
using Microsoft.AspNetCore.Identity;
using VeroEqulibraFit.Infrastructure.Data;

var builder = WebApplication.CreateBuilder(args);
JwtTokenService.ValidateConfiguration(builder.Configuration);
GeminiAiClient.ValidateConfiguration(builder.Configuration);
builder.Services.AddSingleton<ExerciseSearchService>();
builder.Services.AddControllers();
builder.Services.AddHttpClient<GeminiAiClient>(client =>
{
    var baseUrl = builder.Configuration["AI:BaseUrl"];
    if (!string.IsNullOrWhiteSpace(baseUrl))
    {
        if (!baseUrl.StartsWith("http://", StringComparison.OrdinalIgnoreCase) && !baseUrl.StartsWith("https://", StringComparison.OrdinalIgnoreCase)) baseUrl = $"http://{baseUrl}";
        client.BaseAddress = new Uri(baseUrl);
    }
    client.Timeout = TimeSpan.FromSeconds(35);
});
var connectionString = builder.Configuration.GetConnectionString("Postgres")
    ?? builder.Configuration["Database:ConnectionString"];
if (!string.IsNullOrWhiteSpace(connectionString))
    builder.Services.AddVeroEqulibraFitInfrastructure(connectionString).AddDefaultTokenProviders();
else
    throw new InvalidOperationException("ConnectionStrings:Postgres must be configured for authentication and data isolation.");
builder.Services.AddDataProtection()
    .PersistKeysToDbContext<VeroEqulibraFitDbContext>()
    .SetApplicationName("VeroEqulibraFitPlus");
builder.Services.AddHealthChecks()
    .AddCheck<PostgresHealthCheck>("postgres", tags: ["ready"]);
builder.Services.AddSingleton<JwtTokenService>();
builder.Services.AddSingleton<IAccountEmailSender, SmtpAccountEmailSender>();
builder.Services.AddAuthentication(JwtBearerDefaults.AuthenticationScheme).AddJwtBearer(options =>
{
    var tokenService = new JwtTokenService(builder.Configuration);
    options.RequireHttpsMetadata = true;
    options.TokenValidationParameters = new TokenValidationParameters
    {
        ValidateIssuer = true,
        ValidIssuer = tokenService.Issuer,
        ValidateAudience = true,
        ValidAudience = tokenService.Audience,
        ValidateLifetime = true,
        ValidateIssuerSigningKey = true,
        IssuerSigningKey = tokenService.SigningKey,
        ClockSkew = TimeSpan.FromSeconds(30),
    };
});
builder.Services.AddAuthorization(options =>
{
    options.AddPolicy("admin", policy => policy.RequireRole(AdminAccessBootstrapper.AdministratorRole));
});
builder.Services.AddRateLimiter(options =>
{
    options.RejectionStatusCode = StatusCodes.Status429TooManyRequests;
    options.AddFixedWindowLimiter("auth-public", limiter =>
    {
        limiter.PermitLimit = 10;
        limiter.Window = TimeSpan.FromMinutes(1);
        limiter.QueueLimit = 0;
        limiter.AutoReplenishment = true;
    });
});
var app = builder.Build();
await AdminAccessBootstrapper.ApplyAsync(app.Services, builder.Configuration, app.Logger);
var forwardedHeaders = new ForwardedHeadersOptions
{
    ForwardedHeaders = ForwardedHeaders.XForwardedFor | ForwardedHeaders.XForwardedProto,
    ForwardLimit = 1,
};
var configuredProxy = builder.Configuration["ReverseProxy:KnownProxy"];
if (string.Equals(builder.Environment.EnvironmentName, "Production", StringComparison.OrdinalIgnoreCase))
{
    // Render terminates TLS at the edge. Ignore forwarded headers unless an
    // explicit, trusted proxy address is configured; accepting arbitrary
    // X-Forwarded-* headers would allow scheme/client-IP spoofing.
    if (IPAddress.TryParse(configuredProxy, out var proxy))
        forwardedHeaders.KnownProxies.Add(proxy);
}
app.UseForwardedHeaders(forwardedHeaders);
app.UseRateLimiter();
app.UseAuthentication();
app.UseAuthorization();
// Liveness proves only that the process is running. Readiness also checks the
// isolated PostgreSQL dependency; neither endpoint proves user flows work.
app.MapHealthChecks("/health/live", new HealthCheckOptions { Predicate = _ => false });
app.MapHealthChecks("/health/ready", new HealthCheckOptions { Predicate = check => check.Tags.Contains("ready") });
// A public API URL can host account links while the app has no custom domain.
// Only the token already generated by ASP.NET Identity is forwarded; it is not
// logged or persisted by this endpoint.
app.MapGet("/confirm-email", (HttpRequest request) => RedirectToApp(request, "/confirm-email"));
app.MapGet("/reset-password", (HttpRequest request) => RedirectToApp(request, "/reset-password"));
app.MapControllers();
app.Run();

static IResult RedirectToApp(HttpRequest request, string route)
{
    var userId = request.Query["userId"].ToString();
    var token = request.Query["token"].ToString();
    if (string.IsNullOrWhiteSpace(userId) || string.IsNullOrWhiteSpace(token))
        return Results.BadRequest();
    var target = $"veroequilibrafit://account{route}?userId={Uri.EscapeDataString(userId)}&token={Uri.EscapeDataString(token)}";
    return Results.Redirect(target);
}

